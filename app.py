def get_groq_key() -> str | None:
    key = st.session_state.get("manual_key")
    if key:
        return key
    try:
        key = st.secrets.get("GROQ_API_KEY")
    except Exception:  # noqa: BLE001
        key = None
    return key or os.environ.get("GROQ_API_KEY")


def query_material(material: str, api_key: str) -> dict:
    from groq import Groq
    client = Groq(api_key=api_key)
    resp = client.chat.completions.create(
        model=MODEL,
        max_tokens=1200,
        temperature=0.3,
        messages=[
            {"role": "system", "content": SYSTEM_PROMPT},
            {"role": "user", "content": f"Material: {material}"},
        ],
    )
    text = (resp.choices[0].message.content or "").strip()
    text = re.sub(r"^```(json)?|```$", "", text.strip(), flags=re.MULTILINE).strip()
    start, end = text.find("{"), text.rfind("}")
    if start != -1 and end != -1 and end > start:
        text = text[start:end + 1]
    return json.loads(text)


@st.cache_data(show_spinner=False, ttl=86400)
def find_material_image(material: str, dark_mode: bool) -> str:
    """Look up a reference photo for the material via Wikipedia's free
    public API (no key needed). Falls back to a clean text placeholder
    (via placehold.co, also free/no key) if nothing is found, so a
    photo always renders and the material is always easy to identify —
    never raises, so a missed lookup never breaks the app."""
    candidates = [material, f"{material} (material)", f"{material} construction"]
    for name in candidates:
        try:
            url = "https://en.wikipedia.org/api/rest_v1/page/summary/" + name.strip().replace(" ", "_")
            r = requests.get(url, timeout=6, headers={"User-Agent": "MatGuideAI/1.0"})
            if r.status_code == 200:
                thumb = r.json().get("thumbnail", {}).get("source")
                if thumb:
                    return thumb
        except Exception:  # noqa: BLE001
            continue
    label = quote_plus(material.strip()[:30] or "Material")
    bg = "4FA8E0" if dark_mode else "1F4E79"
    return f"https://placehold.co/600x360/{bg}/FFFFFF.png?text={label}&font=roboto"


def add_to_history(material: str, data: dict) -> None:
    st.session_state.history = [h for h in st.session_state.history if h["material"].lower() != material.lower()]
    st.session_state.history.insert(0, {"material": material, "data": data, "time": datetime.now().strftime("%H:%M")})
    st.session_state.history = st.session_state.history[:MAX_HISTORY]


def build_pdf(material: str, data: dict) -> bytes:
    from fpdf import FPDF

    def clean(txt: str) -> str:
        # fpdf2's core font only supports latin-1; swap anything else
        # out rather than crashing the PDF build.
        return (txt or "").encode("latin-1", errors="replace").decode("latin-1")

    pdf = FPDF()
    pdf.add_page()
    pdf.set_font("Helvetica", "B", 18)
    pdf.set_text_color(31, 78, 121)
    pdf.set_x(pdf.l_margin)
    pdf.multi_cell(0, 10, clean(f"MatGuide AI - {material}"))
    pdf.set_font("Helvetica", "", 10)
    pdf.set_text_color(120, 120, 120)
    pdf.set_x(pdf.l_margin)
    pdf.multi_cell(0, 6, clean("AI-generated - verify against local specification/BOQ before use."))
    pdf.ln(4)

    for key, title in SECTIONS:
        content = (data.get(key) or "").strip()
        if not content:
            continue
        pdf.set_font("Helvetica", "B", 12)
        pdf.set_text_color(31, 78, 121)
        pdf.set_x(pdf.l_margin)
        pdf.multi_cell(0, 8, clean(title.upper()))
        pdf.set_font("Helvetica", "", 11)
        pdf.set_text_color(20, 20, 20)
        pdf.set_x(pdf.l_margin)
        pdf.multi_cell(0, 6, clean(content))
        pdf.ln(3)

    out = pdf.output()
    return bytes(out)


def render_rate_card(material: str) -> None:
    """If the searched material matches a known rate category, show a
    reference-price card for the selected city."""
    rate_key = match_rate_key(material)
    if not rate_key:
        return
    info = RATES[rate_key]
    rate = info[st.session_state.city]

    st.markdown(
        f'<div class="rate-card">'
        f'<div class="section-title">📈 Reference Rate — {st.session_state.city}</div>'
        f'{info["label"]}: <b>PKR {rate:,}</b> {info["unit"]}'
        f'<div style="font-size:.75rem;color:{SUBTEXT};margin-top:4px;">'
        f'As of {RATES_LAST_UPDATED} — confirm with your local dealer before purchasing.</div>'
        f'</div>',
        unsafe_allow_html=True,
    )


def whatsapp_link(material: str, data: dict) -> str:
    intro = (data.get("introduction") or "")[:200]
    text = f"*{material}* — via MatGuide AI\n\n{intro}\n\nCheck the full guide: {APP_URL}"
    return f"https://wa.me/?text={quote(text)}"


def render_result(material: str, data: dict) -> None:
    st.write("")

    st.image(find_material_image(material, st.session_state.dark_mode), caption=material, use_container_width=True)

    render_rate_card(material)

    fav_key = material.lower()
    c1, c2, c3 = st.columns(3)
    with c1:
        if fav_key in st.session_state.favorites:
            if st.button("★ Unsave", use_container_width=True):
                del st.session_state.favorites[fav_key]
                st.rerun()
        else:
            if st.button("☆ Save", use_container_width=True):
                st.session_state.favorites[fav_key] = {"material": material, "data": data}
                st.rerun()
    with c2:
        st.download_button(
            "📥 PDF",
            data=build_pdf(material, data),
            file_name=f"{material.strip().replace(' ', '_')}_MatGuide.pdf",
            mime="application/pdf",
            use_container_width=True,
        )
    with c3:
        st.link_button("💬 Share", whatsapp_link(material, data), use_container_width=True)

    st.write("")
    for key, title in SECTIONS:
        content = data.get(key, "").strip()
        if content:
            st.markdown(
                f'<div class="section-card"><div class="section-title">{title}</div>{content}</div>',
                unsafe_allow_html=True,
            )
    st.caption("AI-generated — verify grades, strengths, and codes against your local specification/BOQ before use.")


