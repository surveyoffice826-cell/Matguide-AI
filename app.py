"""
MatGuide AI — Construction Material Guide Assistant
------------------------------------------------------
Type any construction material name and get a structured guide:
introduction, composition, properties, purpose/use, types/grades,
standards, precautions, and alternatives — generated by an LLM
through the Groq API. Also supports recent-search history,
favorites/bookmarks, a reference photo (via Wikipedia, with a
placeholder fallback), reference market rates for 3 Pakistani
cities, a unit converter, dark/light theme, WhatsApp sharing,
side-by-side material comparison, and PDF download of the guide.

Run:
    streamlit run app.py

API key:
    Set GROQ_API_KEY in .streamlit/secrets.toml (see
    .streamlit/secrets.toml.example) or as an environment variable.
    You can also paste a key directly in the sidebar for a quick local
    test — it is only kept in memory for this session, never saved
    to disk or committed anywhere.

Note on History / Favorites:
    These are kept in the browser session only (st.session_state).
    They reset if you refresh the page or close the tab — this app
    has no database, so nothing is saved permanently across visits.

Note on Live Rates:
    There is no free, public, real-time API for construction material
    prices in Pakistan. RATES below is a manually-maintained reference
    table (not a live feed) — update the numbers here whenever you
    have newer data. Current values are sourced from Pakistan Bureau
    of Statistics city-level CPI data (Jan 2026) via a news report,
    reflected as of this app's last code update.
"""

